function blockWith(persons: number, income: number): PopBlock {
  const male = new Uint32Array(81);
  const female = new Uint32Array(81);
  male[30] = Math.floor(persons / 2);
  female[30] = persons - Math.floor(persons / 2);
  return {
    maleByAge: male,
    femaleByAge: female,
    incomeSmoothedRUSDPerCapitaDay: income,
    dwellings: 0,
    housingReferencePersonsPerDwelling: 0,
    housingReferenceIncomeRUSDPerCapitaDay: 0,
  } as unknown as PopBlock;
}

describe("P6 housing", () => {
  test("creation splits the census stock by persons × income^ε with crowding 1.0", () => {
    const poor = blockWith(800, 2);
    const rich = blockWith(200, 20);
    initialiseProvinceHousing([poor, rich], 5);
    expect(poor.dwellings + rich.dwellings).toBeCloseTo(1000 / 5, 9);
    expect(rich.dwellings / 200).toBeGreaterThan(poor.dwellings / 800);
    expect(blockCrowding(poor)).toBe(1);
    expect(blockCrowding(rich)).toBe(1);
    expect(desiredDwellings(poor)).toBeCloseTo(poor.dwellings, 9);
    expect(provinceCrowding([poor, rich], 5)).toBe(1);
  });

  test("depreciation conserves dwellings and crowding rises only above the 1900 level", () => {
    const block = blockWith(1000, 5);
    initialiseProvinceHousing([block], 5);
    const before = block.dwellings;
    let removed = 0;
    for (let day = 0; day < 365; day += 1) removed += depreciateDwellings(block, 365);
    expect(block.dwellings + removed).toBeCloseTo(before, 9);
    expect(removed / before).toBeCloseTo(1 - Math.pow(1 - DWELLING_DEPRECIATION_RATE_PER_YEAR / 365, 365), 9);
    expect(blockCrowding(block)).toBeGreaterThan(1);
    expect(crowdingMortalityFactor(blockCrowding(block), 0.5)).toBeGreaterThan(1);
    expect(crowdingMortalityFactor(0.8, 0.5)).toBe(1);
    expect(desiredDwellings(block)).toBeGreaterThan(block.dwellings);
  });

  test("adult equivalents follow Atwater's scale", () => {
    const block = blockWith(0, 0);
    block.maleByAge[30] = 1;
    block.femaleByAge[30] = 1;
    block.maleByAge[1] = 1;
    expect(adultEquivalents(block)).toBeCloseTo(1 + 0.8 + 0.3, 12);
  });
});

