/**
 * P6 (D-153): the linear expenditure system, saving and housing.
 *
 * - Pure plan (population/demandSystem.ts): adding-up, committed first, homogeneity,
 *   food share falling with income (acceptance, property over a deterministic grid),
 *   substitution toward the cheaper good (acceptance), saving rising with income and
 *   by stratum, gated goods, the exact integral of the marginal-share schedule.
 * - Housing (population/housing.ts): crowding 1.0 at creation, desired stock equal to
 *   the stock at creation, depreciation conserving dwellings, crowding mortality only
 *   above the 1900 level.
 * - Integrated days on the M3 small economy with a demand system and housing: rows are
 *   generated by the system, dwellings are conserved through purchases and
 *   depreciation (acceptance), the day is deterministic, and the save round-trips
 *   (acceptance). D-155: every economy world has a demand system (the tier path was removed).
 */

