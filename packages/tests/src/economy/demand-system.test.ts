function p6Scenario(): EconomyScenarioDef {
  const base = loadM3SmallEconomy();
  const demandSystem: DemandSystemDef = {
    commerceGoodKey: "food-products",
    transportGoodKey: "food-products",
    categories: [
      {
        key: "food",
        substitutionElasticity: 1.5,
        committedAtSubsistenceTier: true,
        goods: [
          { goodKey: "grain", committedPerAdultEquivalentPerDay: 0.9, retailCommercePerUnit: 0, retailTransportPerUnit: 0 },
          { goodKey: "food-products", committedPerAdultEquivalentPerDay: 0.08, retailCommercePerUnit: 0, retailTransportPerUnit: 0 },
          { goodKey: "fish", committedPerAdultEquivalentPerDay: 0.03, retailCommercePerUnit: 0, retailTransportPerUnit: 0 },
          { goodKey: "livestock", committedPerAdultEquivalentPerDay: 0.03, retailCommercePerUnit: 0, retailTransportPerUnit: 0 },
        ],
      },
      {
        key: "clothing",
        substitutionElasticity: 1.2,
        committedAtSubsistenceTier: false,
        goods: [
          { goodKey: "clothing", committedPerAdultEquivalentPerDay: 0.01, retailCommercePerUnit: 0, retailTransportPerUnit: 0 },
          { goodKey: "textiles", committedPerAdultEquivalentPerDay: 0, retailCommercePerUnit: 0, retailTransportPerUnit: 0 },
        ],
      },
    ],
    knots: [
      { consumptionRatio: 1.5, marginalShares: { food: 0.5, clothing: 0.5 }, goodWeights: { food: { livestock: 0.5, fish: 0.3, "food-products": 0.2 }, clothing: { clothing: 0.8, textiles: 0.2 } } },
      { consumptionRatio: 20, marginalShares: { food: 0.2, clothing: 0.8 }, goodWeights: { food: { livestock: 0.6, fish: 0.2, "food-products": 0.2 }, clothing: { clothing: 0.6, textiles: 0.4 } } },
    ],
    tastes: [],
    // Wool stands in for the dwelling good in this fixture (it has a seller).
    dwellingGoodKey: "wool",
  };
  return {
    ...base,
    population: {
      ...base.population,
      definitions: { ...base.population.definitions, demandSystem },
      provinceEconomies: base.population.provinceEconomies.map((province) => ({ ...province, housingReferencePersonsPerDwelling: 5 })),
      popBlocks: base.population.popBlocks.map((block, index) => ({ ...block, incomeRUSDPerCapitaDay: [0.1, 0.3, 0.8, 2][index] ?? 0.1 })),
    },
  };
}

function totalDwellings(world: World): number {
  return world.popBlocks.reduce((sum, block) => sum + block.dwellings, 0);
}

describe("P6 integrated days", () => {
  test("a demand-system world starts with crowding 1, conserves dwellings, money and is deterministic", () => {
    const scenario = p6Scenario();
    const context = economyTickContext(scenario);
    const world = createEconomyWorld(scenario);
    for (const block of world.popBlocks) expect(blockCrowding(block)).toBe(1);
    const persons = world.popBlocks.reduce((sum, block) => sum + populationTotal(block), 0);
    expect(totalDwellings(world)).toBeCloseTo(persons / 5, 6);
    const cash = totalCash(world);
    let bought = 0;
    let depreciated = 0;
    const current = world;
    const start = totalDwellings(world);
    for (let day = 0; day < 20; day += 1) {
      const result = tick(current, context);
      const demand = result.economy?.demand ?? null;
      expect(demand).not.toBeNull();
      bought += demand?.housing.dwellingsBought ?? 0;
      depreciated += demand?.housing.dwellingsDepreciated ?? 0;
      expect(current.markets[0]?.priceSmoothedRUSD.length).toBe(current.markets[0]?.priceRUSD.length);
    }
    // Acceptance: dwellings are conserved through purchases and depreciation.
    expect(totalDwellings(current)).toBeCloseTo(start + bought - depreciated, 9);
    expect(totalCash(current)).toBeCloseTo(cash, 3);
    // Smoothed income moves from its initial value.
    expect(current.popBlocks.some((block) => block.incomeSmoothedRUSDPerCapitaDay > 0)).toBe(true);

    // Determinism.
    const replay = createEconomyWorld(scenario);
    for (let day = 0; day < 20; day += 1) tick(replay, context);
    expect(hashWorld(replay)).toBe(hashWorld(current));

    // Acceptance: save round trip, then the next day matches.
    const restored = deserializeWorld(serializeWorld(current));
    expect(hashWorld(restored)).toBe(hashWorld(current));
    expect(encodeWorld(current).popBlocks[0]).toHaveProperty("dwellings");
    tick(restored, context);
    tick(current, context);
    expect(hashWorld(restored)).toBe(hashWorld(current));
  });
});
