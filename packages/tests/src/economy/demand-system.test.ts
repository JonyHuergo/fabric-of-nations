// ---------------------------------------------------------------------------
// A small synthetic system: food (grain, meat; committed grain) and clothing
// (cloth; committed cloth), with the food marginal share falling from 0.6 to 0.2.
// ---------------------------------------------------------------------------
const GOODS = [
  { id: 0, key: "grain", basePrice1900RUSD: 1 },
  { id: 1, key: "meat", basePrice1900RUSD: 4 },
  { id: 2, key: "cloth", basePrice1900RUSD: 10 },
  { id: 3, key: "shop", basePrice1900RUSD: 1 },
  { id: 4, key: "lamp", basePrice1900RUSD: 5 },
] as const;

const SYSTEM: DemandSystemDef = {
  commerceGoodKey: "shop",
  transportGoodKey: "shop",
  categories: [
    {
      key: "food",
      substitutionElasticity: 1.5,
      committedAtSubsistenceTier: true,
      goods: [
        { goodKey: "grain", committedPerAdultEquivalentPerDay: 0.5, retailCommercePerUnit: 0.2, retailTransportPerUnit: 0 },
        { goodKey: "meat", committedPerAdultEquivalentPerDay: 0, retailCommercePerUnit: 0.5, retailTransportPerUnit: 0 },
      ],
    },
    {
      key: "other",
      substitutionElasticity: 1,
      committedAtSubsistenceTier: false,
      goods: [
        { goodKey: "cloth", committedPerAdultEquivalentPerDay: 0.01, retailCommercePerUnit: 1, retailTransportPerUnit: 0 },
        { goodKey: "lamp", committedPerAdultEquivalentPerDay: 0, retailCommercePerUnit: 0, retailTransportPerUnit: 0, requiredTechnologyKey: "lighting" },
      ],
    },
  ],
  knots: [
    { consumptionRatio: 2, marginalShares: { food: 0.6, other: 0.4 }, goodWeights: { food: { grain: 0.7, meat: 0.3 }, other: { cloth: 0.8, lamp: 0.2 } } },
    { consumptionRatio: 10, marginalShares: { food: 0.2, other: 0.8 }, goodWeights: { food: { grain: 0.3, meat: 0.7 }, other: { cloth: 0.5, lamp: 0.5 } } },
  ],
  tastes: [{ countryKey: "TEA", goodKey: "meat", weightMultiplier: 0 }],
  dwellingGoodKey: null,
};

const system = resolveDemandSystem(SYSTEM, GOODS, new Map([["lighting", 7]]));
const ALL = new Uint8Array([1, 1, 1, 1, 1]);
const PRICES = [1, 4, 10, 1, 5];

function input(overrides: Partial<DemandPlanInput> = {}): DemandPlanInput {
  return {
    adultEquivalents: 4,
    persons: 5,
    incomePerCapitaDay: 3,
    cash: 1000,
    marginalPropensityToConsume: 0.9,
    urbanShare: 0.5,
    prices: PRICES,
    available: ALL,
    taste: null,
    wealthConsumptionRatePerYear: 0,
    cashReserveDays: 30,
    daysInYear: 365,
    ...overrides,
  };
}

function plan(overrides: Partial<DemandPlanInput> = {}) {
  const out = createDemandPlanOutput(system);
  planHouseholdDemand(system, input(overrides), out);
  return out;
}

/** Spending at retail prices by good. */
function spending(out: ReturnType<typeof plan>): number[] {
  return GOODS.map((good) => ((out.committed[good.id] ?? 0) + (out.supernumerary[good.id] ?? 0)) * (out.retailPrice[good.id] ?? 0));
}

describe("P6 demand system: the plan", () => {
  test("the cumulative schedule integrates the piecewise-linear shares exactly and adds up", () => {
    for (const x of [1, 1.5, 2, 3.7, 10, 25]) {
      const total = cumulativeSupernumeraryShare(system, 0, x) + cumulativeSupernumeraryShare(system, 1, x);
      expect(total).toBeCloseTo(x - 1, 12);
    }
    // Below the first knot the share is constant (0.6); between knots the mean share.
    expect(cumulativeSupernumeraryShare(system, 0, 2)).toBeCloseTo(0.6, 12);
    expect(cumulativeSupernumeraryShare(system, 0, 10)).toBeCloseTo(0.6 + 8 * 0.4, 12);
    expect(cumulativeSupernumeraryShare(system, 0, 12)).toBeCloseTo(0.6 + 8 * 0.4 + 2 * 0.2, 12);
  });

  test("adding-up: spending equals planned consumption and consumption + saving = income", () => {
    const out = plan();
    const spent = spending(out).reduce((sum, value) => sum + value, 0);
    expect(spent).toBeCloseTo(out.consumption, 9);
    const saving = out.income - out.consumption;
    expect(saving).toBeCloseTo((1 - 0.9) * (out.income - out.committedCost), 9);
    expect(out.categorySpend.reduce((sum, value) => sum + value, 0)).toBeCloseTo(out.consumption, 9);
  });

  test("below subsistence only the committed quantities are planned", () => {
    const out = plan({ incomePerCapitaDay: 0.1 });
    expect(out.supernumerary.every((value) => value === 0)).toBe(true);
    expect(out.committed[0]).toBeCloseTo(0.5 * 4, 12);
    expect(out.committed[2]).toBeCloseTo(0.01 * 4, 12);
  });

  test("homogeneity: prices, income and cash × k leave quantities unchanged", () => {
    const base = plan();
    const scaled = plan({ prices: PRICES.map((price) => price * 3), incomePerCapitaDay: 9, cash: 3000 });
    for (const good of GOODS) {
      expect(scaled.committed[good.id]).toBeCloseTo(base.committed[good.id] ?? 0, 9);
      expect(scaled.supernumerary[good.id]).toBeCloseTo(base.supernumerary[good.id] ?? 0, 9);
    }
  });

  test("acceptance: the food expenditure share falls with income (property over a grid)", () => {
    // In an LES the food share falls with income whenever food's share of the committed
    // basket exceeds its marginal share at the bottom of the schedule (0.6 here) and the
    // marginal share does not rise; the 1900 data are checked for this condition by the
    // generator and the 1900-world test.
    const priceSets = [PRICES, [2, 4, 10, 1, 5], [1, 8, 5, 2, 5], [0.5, 2, 20, 1, 5], [3, 6, 4, 1, 5]];
    for (const prices of priceSets) {
      for (const urbanShare of [0, 0.5, 1]) {
        const atSubsistence = plan({ prices, urbanShare, incomePerCapitaDay: 0 });
        const committedFoodShare = (atSubsistence.categorySpend[0] ?? 0) / atSubsistence.committedCost;
        if (!(committedFoodShare > 0.6)) continue;
        for (const mpc of [0.6, 0.85, 0.94]) {
          let previous = Infinity;
          for (let step = 0; step <= 60; step += 1) {
            const income = 0.5 * Math.pow(1.12, step);
            const out = plan({ prices, urbanShare, marginalPropensityToConsume: mpc, incomePerCapitaDay: income });
            const share = (out.categorySpend[0] ?? 0) / out.consumption;
            if (out.ratio > 1) expect(share).toBeLessThan(previous + 1e-12);
            previous = share;
          }
        }
      }
    }
  });

  test("acceptance: substitution moves demand toward the cheaper good", () => {
    const before = plan({ incomePerCapitaDay: 6 });
    const after = plan({ incomePerCapitaDay: 6, prices: [1, 2, 10, 1, 5] });
    const ratioBefore = (before.supernumerary[1] ?? 0) / (before.supernumerary[0] ?? 1);
    const ratioAfter = (after.supernumerary[1] ?? 0) / (after.supernumerary[0] ?? 1);
    expect(ratioAfter).toBeGreaterThan(ratioBefore);
    expect(after.supernumerary[1]).toBeGreaterThan(before.supernumerary[1] ?? 0);
  });

  test("saving rises with income and falls with the propensity to consume", () => {
    const rate = (income: number, mpc: number): number => {
      const out = plan({ incomePerCapitaDay: income, marginalPropensityToConsume: mpc });
      return (out.income - out.consumption) / out.income;
    };
    expect(rate(2, 0.94)).toBeLessThan(rate(6, 0.94));
    expect(rate(6, 0.94)).toBeLessThan(rate(6, 0.85));
    expect(rate(6, 0.85)).toBeLessThan(rate(6, 0.6));
    // Below subsistence the block dissaves to buy its committed quantities.
    expect(rate(0.1, 0.6)).toBeLessThan(0);
  });

  test("consumption out of wealth adds spending only above the reserve", () => {
    const lean = plan({ wealthConsumptionRatePerYear: 0.04, cash: 0 });
    const rich = plan({ wealthConsumptionRatePerYear: 0.04, cash: 1e6 });
    expect(lean.income).toBeCloseTo(15, 12);
    expect(rich.income).toBeGreaterThan(lean.income);
  });

  test("a closed gate or a zero taste removes a good and its category share goes to the rest", () => {
    const open = plan({ incomePerCapitaDay: 8 });
    const closed = plan({ incomePerCapitaDay: 8, available: new Uint8Array([1, 1, 1, 1, 0]) });
    expect(closed.supernumerary[4]).toBe(0);
    expect(closed.supernumerary[2]).toBeGreaterThan(open.supernumerary[2] ?? 0);
    const sum = (out: ReturnType<typeof plan>): number => spending(out).reduce((acc, value) => acc + value, 0);
    expect(sum(closed)).toBeCloseTo(sum(open), 9);
    const taste = new Float64Array([1, 0, 1, 1, 1]);
    expect(plan({ incomePerCapitaDay: 8, taste }).supernumerary[1]).toBe(0);
  });

  test("invalid definitions are rejected", () => {
    const bad = { ...SYSTEM, knots: [{ ...SYSTEM.knots[0]!, marginalShares: { food: 0.6, other: 0.3 } }] };
    expect(() => resolveDemandSystem(bad, GOODS, new Map([["lighting", 7]]))).toThrow(/sum/);
    const backwards = { ...SYSTEM, knots: [SYSTEM.knots[1]!, SYSTEM.knots[0]!] };
    expect(() => resolveDemandSystem(backwards, GOODS, new Map([["lighting", 7]]))).toThrow(/increase/);
  });
});

