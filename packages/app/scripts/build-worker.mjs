/**
 * Generate the browser/WebView worker bundle used by the Expo app.
 *
 * The worker bundle is committed as `src/generated/simWorker.ts` so a clean
 * checkout can typecheck and bundle without first building `packages/sim`.
 * Regenerate after changing sim-worker, sim, or the historical sample:
 *
 *   pnpm -F @century/app build:worker
 *
 * The bundle aliases `@century/sim` to TypeScript source and maps its relative
 * `.js` imports to `.ts`, so no prior build artifact is required.
 */

import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const esbuild = require("esbuild");

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, "..");
const WORKSPACE_ROOT = resolve(APP_ROOT, "../..");
const SIM_SOURCE_ROOT = resolve(WORKSPACE_ROOT, "packages/sim/src");
const WORKER_ENTRY = resolve(WORKSPACE_ROOT, "packages/sim-worker/src/webWorkerEntry.ts");
const OUTPUT = resolve(APP_ROOT, "src/generated/simWorker.ts");

const simSourceResolver = {
  name: "sim-source-js-to-ts",
  setup(build) {
    build.onResolve({ filter: /\.js$/ }, (args) => {
      if (!args.importer.startsWith(SIM_SOURCE_ROOT)) return null;
      const candidate = resolve(args.resolveDir, args.path.replace(/\.js$/, ".ts"));
      return { path: candidate };
    });
  },
};

const result = await esbuild.build({
  entryPoints: [WORKER_ENTRY],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  alias: {
    "@century/sim": resolve(SIM_SOURCE_ROOT, "index.ts"),
  },
  plugins: [simSourceResolver],
});

const output = result.outputFiles?.[0];
if (output === undefined) throw new Error("esbuild produced no worker output");
const script = output.text;
if (!script.includes("SimulationHost") && !script.includes("READY")) {
  throw new Error("worker bundle does not look like the Century worker entry");
}
const escapedScript = script.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/></head><body><script>${escapedScript}</script></body></html>`;

const source = `/**
 * Generated by packages/app/scripts/build-worker.mjs. Do not edit by hand.
 *
 * The app never imports simulation implementation code: it sends the committed
 * worker script/HTML to a Web Worker or hidden WebView.
 */
export const SIM_WORKER_SCRIPT = ${JSON.stringify(script)};
export const SIM_WORKER_HTML = ${JSON.stringify(html)};
export const SIM_WORKER_BUNDLE_BYTES = ${String(Buffer.byteLength(script, "utf8"))};
export const SIM_WORKER_HTML_BYTES = ${String(Buffer.byteLength(html, "utf8"))};
`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, source, "utf8");
console.log(
  `wrote ${OUTPUT}: script ${(Buffer.byteLength(script, "utf8") / 1024).toFixed(1)} KiB, ` +
    `html ${(Buffer.byteLength(html, "utf8") / 1024).toFixed(1)} KiB`,
);
