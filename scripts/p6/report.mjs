/**
 * P6 (D-153): generated documents of the demand system.
 * - docs/P6_BEFORE_AFTER.md: the schedule, the committed basket, the margins, the 1900
 *   household spending by country, coverage and modelled ÷ sourced output.
 * - docs/P6_DEMAND_PROVENANCE.md: every P6 source with its licence, and every parameter
 *   with its status.
 */

const fmt = (value, digits = 3) => (value === null || value === undefined || !Number.isFinite(value) ? "—" : Number(value).toPrecision(digits));
const pct = (value) => (value === null || value === undefined ? "—" : `${(100 * value).toFixed(1)} %`);

export function p6BeforeAfterReport(calibration, demandSystem) {
  const p6 = calibration.p6;
  const lines = [];
  lines.push("# P6 before and after: Engel demand, saving and housing");
  lines.push("");
  lines.push("Generated by `node scripts/p5b/build-goods-1900.mjs` (P6 stage: `scripts/p6/demand.mjs`); do not edit by hand. Decision D-153, plan `docs/P6_PLAN.md`. Sources and licences: `docs/P6_DEMAND_PROVENANCE.md`.");
  lines.push("");
  lines.push("## Committed basket");
  lines.push("");
  lines.push(`Adult equivalents per person in the 1900 world (Atwater scale on the P4 age structures): ${fmt(p6.committed.worldAdultEquivalentsPerPerson, 4)}. Committed cost per adult equivalent at reference retail prices (urban household): ${fmt(p6.committedCostPerAdultEquivalentRUSD, 4)} RUSD a day.`);
  lines.push("");
  lines.push("| Good | Committed per adult equivalent per day |");
  lines.push("|---|---:|");
  for (const [key, value] of Object.entries(p6.committed.perAdultEquivalentPerDay)) lines.push(`| ${key} | ${fmt(value, 4)} |`);
  lines.push("");
  lines.push("## Marginal-share schedule");
  lines.push("");
  const categories = demandSystem.categories.map((category) => category.key);
  lines.push(`| Knot | Consumption ratio | ${categories.join(" | ")} |`);
  lines.push(`|---|---:|${categories.map(() => "---:").join("|")}|`);
  const names = Object.keys(p6.knotFits).sort((a, b) => p6.knotFits[a].meanRatio - p6.knotFits[b].meanRatio);
  demandSystem.knots.forEach((knot, index) => {
    lines.push(`| ${names[index] ?? index} | ${fmt(knot.consumptionRatio, 4)} | ${categories.map((key) => fmt(knot.marginalShares[key] ?? 0, 3)).join(" | ")} |`);
  });
  lines.push("");
  lines.push("Each knot holds the local slopes of its budget set (category spending ÷ committed cost on the consumption ratio); a negative slope is set to 0 and the shares renormalised. Raw slope sums: " + names.map((name) => `${name} ${fmt(p6.knotFits[name].slopeSum, 3)}`).join(", ") + ".");
  lines.push("");
  lines.push("## Retail margins (urban household)");
  lines.push("");
  lines.push("| Good | Retail ÷ reference − 1 | Commerce units per unit | Transport units per unit | Status |");
  lines.push("|---|---:|---:|---:|---|");
  for (const [key, margin] of Object.entries(p6.margins.byGood)) lines.push(`| ${key} | ${fmt(margin.rate, 3)} | ${fmt(margin.commerce, 4)} | ${fmt(margin.transport, 4)} | ${margin.status} |`);
  lines.push("");
  if (p6.tastes && Object.keys(p6.tastes).length > 0) {
    lines.push("## National tastes (weight multipliers relative to the United States)");
    lines.push("");
    lines.push("| Country | Coffee, tea and cocoa | Sugar | Relative GDP per head |");
    lines.push("|---|---:|---:|---:|");
    for (const [tag, row] of Object.entries(p6.tastes)) lines.push(`| ${tag} | ${fmt(row.ctc)} | ${fmt(row.sugar)} | ${fmt(row.relativeGdpPerHead)} |`);
    lines.push("");
  }
  lines.push("## 1900 household spending by country (planned at opening prices)");
  lines.push("");
  lines.push("| Country | Persons | Income per head (RUSD/yr) | Consumption per head (RUSD/yr) | Food share | Blocks spending above income |");
  lines.push("|---|---:|---:|---:|---:|---:|");
  for (const [tag, row] of Object.entries(p6.countries ?? {})) {
    lines.push(`| ${tag} | ${row.persons.toLocaleString("en-US")} | ${fmt(row.incomeRUSDPerCapitaYear, 4)} | ${fmt(row.consumptionRUSDPerCapitaYear, 4)} | ${pct(row.foodShare)} | ${row.blocksAboveIncome} |`);
  }
  lines.push("");
  lines.push("A block spends above its income only below subsistence, when it dissaves to buy its committed quantities (plan §2.1).");
  lines.push("");
  const coverage = calibration.coverage?.world;
  if (coverage !== undefined) {
    lines.push("## Coverage");
    lines.push("");
    lines.push(`Covered value added ${fmt(coverage.coveredAfterRUSDPerYear / 1e9, 4)} bn RUSD a year, ${pct(coverage.shareAfter)} of world GDP (P2b before: ${pct(coverage.shareBefore)}; P5b close: 40.7 %).`);
    const above = Object.entries(calibration.coverage.territories).filter(([, territory]) => territory.shareAfter > 1).map(([key]) => key);
    lines.push("");
    lines.push(`Territories above 100 % of GDP: ${above.length}${above.length > 0 ? ` (${above.join(", ")})` : ""}.`);
    lines.push("");
  }
  const sourced = calibration.placement?.modelledOverSourced;
  if (sourced !== undefined) {
    lines.push("## Modelled ÷ sourced 1900 output");
    lines.push("");
    lines.push("| Good | Modelled ÷ sourced |");
    lines.push("|---|---:|");
    for (const [key, entry] of Object.entries(sourced)) lines.push(`| ${key} | ${entry.modelledOverSourced === null ? "—" : entry.modelledOverSourced.toFixed(2)} |`);
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

export function p6Provenance(sources, calibration) {
  const lines = [];
  lines.push("# P6 demand, saving and housing: provenance");
  lines.push("");
  lines.push("Generated by `node scripts/p5b/build-goods-1900.mjs` from `packages/data/data/historical/p6/sources_1900.json` and the builder's trace; do not edit by hand. Decision D-153.");
  lines.push("");
  lines.push("## Sources and licences");
  lines.push("");
  lines.push("| Id | Title | Author | Licence | Locator notes |");
  lines.push("|---|---|---|---|---|");
  for (const source of sources.sources) lines.push(`| ${source.id} | [${source.title}](${source.url}) | ${source.author} | ${source.licence} | ${source.notes ?? ""} |`);
  lines.push("");
  lines.push("## Source rows");
  lines.push("");
  lines.push("| Row | Source | Locator | Status |");
  lines.push("|---|---|---|---|");
  for (const [key, row] of Object.entries(sources)) {
    if (key === "sources" || typeof row !== "object" || row === null || Array.isArray(row)) continue;
    const sourceId = row.sourceId ?? (row.sourceIds ?? []).join(", ");
    lines.push(`| ${key} | ${sourceId || "—"} | ${row.locator ?? row.note ?? ""} | ${row.status ?? "—"} |`);
  }
  lines.push("");
  lines.push("## Coefficients (simulation constants)");
  lines.push("");
  const c = calibration.p6.coefficients;
  lines.push("| Coefficient | Value | Status |");
  lines.push("|---|---:|---|");
  lines.push(`| Marginal propensity to consume, lower stratum | ${c.marginalPropensityToConsume.lower} | calibrated (1901 survey surplus) |`);
  lines.push(`| Marginal propensity to consume, middle stratum | ${c.marginalPropensityToConsume.middle} | provisional |`);
  lines.push(`| Marginal propensity to consume, upper stratum | ${c.marginalPropensityToConsume.upper} | provisional |`);
  lines.push(`| Consumption out of wealth, per year | ${c.wealthConsumptionRatePerYear} | provisional |`);
  lines.push(`| Cash reserve, days of committed spending | ${c.cashReserveDays} | provisional |`);
  lines.push(`| Dwelling depreciation, per year | ${c.dwellingDepreciationRatePerYear} | provisional (bracketed by Historical Statistics N 156 and BEA) |`);
  lines.push(`| Income elasticity of dwellings per person | ${c.dwellingIncomeElasticity} | calibrated (US 1900–1990) |`);
  lines.push("");
  lines.push("Crowding mortality weights (0.5 child, 0.3 adult), the unrest weight (0.1), the smoothing times (365 days income, 30 days prices) and the Atwater scale are documented in `packages/sim/src/population/constants.ts` and `economy/constants.ts`.");
  lines.push("");
  return `${lines.join("\n")}\n`;
}
