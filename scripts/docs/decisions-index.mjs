#!/usr/bin/env node
/**
 * Decision register index (D-145).
 *
 * Regenerates the index table at the top of `DECISIONS.md` from the entry headings
 * (`## D-NNN — Title` or `### D-NNN — Title`). Only the text between the two index
 * markers is written; every entry stays byte for byte as it is.
 *
 *   node scripts/docs/decisions-index.mjs           rewrite the index
 *   node scripts/docs/decisions-index.mjs --check   fail if the index is stale
 *
 * The check also fails on a duplicate or missing decision number, so the register can
 * never be renumbered silently.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const PATH = join(ROOT, "DECISIONS.md");
const START = "<!-- decisions-index:start (generated by scripts/docs/decisions-index.mjs; do not edit) -->";
const END = "<!-- decisions-index:end -->";

function entries(text) {
  const out = [];
  for (const line of text.split("\n")) {
    // D-101 and D-102 carry a mis-encoded dash ("â€”") in their headings; entries are
    // never edited, so the index accepts both separators and prints a plain dash.
    const match = /^#{2,3} (D-(\d{3})) (?:—|â€”) (.+)$/.exec(line);
    if (match) out.push({ id: match[1], number: Number(match[2]), title: match[3].trim() });
  }
  return out;
}

function validate(list) {
  const errors = [];
  const seen = new Set();
  for (const entry of list) {
    if (seen.has(entry.number)) errors.push(`duplicate ${entry.id}`);
    seen.add(entry.number);
  }
  const max = Math.max(...list.map((entry) => entry.number));
  for (let number = 1; number <= max; number += 1) {
    if (!seen.has(number)) errors.push(`missing D-${String(number).padStart(3, "0")}`);
  }
  return errors;
}

function render(list) {
  const sorted = [...list].sort((a, b) => a.number - b.number);
  const escape = (text) => text.replaceAll("|", "\\|");
  return [
    START,
    "",
    `**Index** — ${String(sorted.length)} decisions, D-001 to ${sorted[sorted.length - 1].id}. Entries below are`,
    "in the order they were recorded; superseded and amended entries are kept as written",
    "and say what replaced them.",
    "",
    "| Decision | Title |",
    "|---|---|",
    ...sorted.map((entry) => `| ${entry.id} | ${escape(entry.title)} |`),
    "",
    END,
  ].join("\n");
}

const text = readFileSync(PATH, "utf8");
const list = entries(text);
const errors = validate(list);
if (errors.length > 0) {
  console.error(`DECISIONS.md register is inconsistent:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start < 0 || end < start) {
  console.error("DECISIONS.md has no index markers");
  process.exit(1);
}
const next = `${text.slice(0, start)}${render(list)}${text.slice(end + END.length)}`;
if (process.argv.includes("--check")) {
  if (next !== text) {
    console.error("DECISIONS.md index is stale: run node scripts/docs/decisions-index.mjs");
    process.exit(1);
  }
  console.log(`DECISIONS.md index is current (${String(list.length)} decisions)`);
} else {
  writeFileSync(PATH, next);
  console.log(`DECISIONS.md index written (${String(list.length)} decisions)`);
}
