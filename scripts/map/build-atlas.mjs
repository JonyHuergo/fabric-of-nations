#!/usr/bin/env node
/**
 * Compiles the map runtime into one self-contained page, the artifact every
 * platform runs:
 *
 *   packages/app/public/map/atlas-v1.html
 *     iOS and Android load it in a WebView from the app's packaged assets; the web
 *     build loads the same file in an iframe. Runtime code, the decode worker, the
 *     render bundle, phone-sized rasters, label fonts and the runtime catalogue are
 *     all inline, so the page needs no file access and no network.
 *
 *   packages/app/src/generated/provinceCatalog.ts
 *     Province metadata without rings, for the React Native bundle. The render
 *     bundle holds the shapes, so the interface need not carry a second copy.
 *
 * Inputs are the outputs of `pnpm map:build`, the province data, the bundled fonts
 * and `packages/app/src/map`. Output is byte-reproducible: `pnpm map:atlas:check`
 * rebuilds in memory and fails if the committed files differ.
 */

import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const APP = resolve(ROOT, "packages/app");
const requireFromApp = createRequire(resolve(APP, "package.json"));
const requireFromRoot = createRequire(resolve(ROOT, "package.json"));
const esbuild = requireFromApp("esbuild");
const Jimp = requireFromRoot("jimp-compact");

const OUT_HTML = resolve(APP, "public/map/atlas-v1.html");
const OUT_CATALOG = resolve(APP, "src/generated/provinceCatalog.ts");
const MAP_DIR = resolve(APP, "public/map");
const DATA_DIR = resolve(ROOT, "packages/data/data/map");

/** Same order as `provinceMapBundle.ts`: bundle index is catalogue index. */
const PROVINCE_FILES = [
  "provinces_1900.json",
  "provinces_asia_1900.json",
  "provinces_africa_1900.json",
  "provinces_americas_1900.json",
  "provinces_oceania_1900.json",
];

/** Rasters are source 1:50m; 2048 texels is what a phone screen can show of them. */
const TEXTURE_WIDTH = 2048;
const TEXTURE_QUALITY = 74;

const checkOnly = process.argv.includes("--check");
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** Evaluate a TypeScript module with no imports worth keeping and read an export. */
function evaluateModule(path, exportName) {
  const { code } = esbuild.transformSync(readFileSync(path, "utf8"), { loader: "ts", format: "cjs" });
  const module = { exports: {} };
  vm.runInNewContext(code, { module, exports: module.exports });
  return module.exports[exportName];
}

async function bundle(entry) {
  const result = await esbuild.build({
    entryPoints: [resolve(APP, entry)],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["es2020", "safari15"],
    minify: true,
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
  });
  const output = result.outputFiles?.[0];
  if (output === undefined) throw new Error(`esbuild produced no output for ${entry}`);
  return output.text;
}

async function texture(file) {
  const image = await Jimp.read(resolve(MAP_DIR, file));
  const source = { width: image.bitmap.width, height: image.bitmap.height };
  image.resize(TEXTURE_WIDTH, Math.round((source.height / source.width) * TEXTURE_WIDTH), Jimp.RESIZE_BILINEAR);
  const bytes = await image.quality(TEXTURE_QUALITY).getBufferAsync(Jimp.MIME_JPEG);
  return { bytes, source };
}

const safeScript = (text) => text.replace(/<\/script/giu, "<\\/script");
const inlineJson = (value) => JSON.stringify(value).replace(/</gu, "\\u003c");

function loadProvinces() {
  const provinces = [];
  const futurePolities = [];
  const seenFuture = new Set();
  for (const file of PROVINCE_FILES) {
    const data = JSON.parse(readFileSync(resolve(DATA_DIR, file), "utf8"));
    provinces.push(...data.provinces);
    for (const polity of data.futurePolities) {
      if (seenFuture.has(polity.polityId)) continue;
      seenFuture.add(polity.polityId);
      futurePolities.push(polity);
    }
  }
  return { provinces, futurePolities };
}

function provinceCatalogSource({ provinces, futurePolities }) {
  const data = {
    futurePolities: futurePolities.map(({ polityId, tag, commonName }) => ({ polityId, tag, commonName })),
    provinces: provinces.map(({ rings, holes, aliases, sourceIds, historicalName, ...rest }) => rest),
  };
  return `/**
 * Generated by scripts/map/build-atlas.mjs. Do not edit by hand.
 *
 * Province metadata in bundle order, without rings. The map runtime draws and
 * picks from the render bundle, so the interface carries no province geometry.
 */
import type { ProvinceCatalogData } from "../provinceCatalogTypes";

export const PROVINCE_CATALOG = (${JSON.stringify(data)}) as unknown as ProvinceCatalogData;
`;
}

function runtimeCatalog({ provinces, futurePolities }, worldCatalog) {
  return {
    provinces: provinces.map((province) => ({
      id: province.id,
      key: province.key,
      displayName: province.displayName,
      mapTag: province.mapTag,
      initialOwnerTag: province.initialOwnerTag,
      initialOwnerPolityId: province.initialOwnerPolityId,
      simulationRegionId: province.simulationRegionId,
      residual: province.residual,
      area: province.area,
      bbox: province.bbox,
      label: province.label,
    })),
    entries: worldCatalog.entries.map((entry) => ({
      id: entry.id,
      tag: entry.tag,
      kind: entry.kind,
      status: entry.status,
      sovereignTag: entry.sovereignTag,
      commonName: entry.commonName,
      capital: entry.capital,
      population1900: entry.population1900,
      market: entry.market,
    })),
    markets: worldCatalog.markets.map((market) => ({ id: market.id, key: market.key })),
    futurePolities: futurePolities.map(({ polityId, tag, commonName }) => ({ polityId, tag, commonName })),
  };
}

async function build() {
  const tokens = await bundleTokens();
  const provinceData = loadProvinces();
  const worldCatalog = evaluateModule(resolve(APP, "src/generated/worldCatalog.ts"), "WORLD_CATALOG");
  const bundleBytes = readFileSync(resolve(MAP_DIR, "world-render-v1.bin"));
  const relief = await texture("relief-v1.jpg");
  const ocean = await texture("ocean-v1.jpg");
  const [runtime, decodeWorker] = await Promise.all([
    bundle("src/map/runtime/main.ts"),
    bundle("src/map/runtime/decodeWorker.ts"),
  ]);
  const faces = tokens.MAP_LABEL_FONTS.map((family) => {
    const bytes = readFileSync(resolve(APP, "assets/fonts", tokens.FONT_FILES[family]));
    return { family, bytes };
  });
  const fontCss = faces
    .map(({ family, bytes }) => `@font-face{font-family:${family};src:url(data:font/ttf;base64,${bytes.toString("base64")}) format("truetype")}`)
    .join("");
  const manifest = {
    format: 1,
    bundleSha256: sha256(bundleBytes),
    reliefSha256: sha256(relief.bytes),
    oceanSha256: sha256(ocean.bytes),
    textureSize: [TEXTURE_WIDTH, Math.round((relief.source.height / relief.source.width) * TEXTURE_WIDTH)],
    fonts: faces.map(({ family, bytes }) => ({ family, sha256: sha256(bytes) })),
    runtimeSha256: sha256(runtime),
    tokensSha256: sha256(readFileSync(resolve(APP, "src/design/tokens.ts"))),
  };
  const csp = [
    "default-src 'none'",
    "script-src 'unsafe-inline' blob:",
    "style-src 'unsafe-inline'",
    "font-src data:",
    "img-src data: blob:",
    "connect-src data: blob:",
    "worker-src blob:",
  ].join("; ");
  const sea = tokens.ERA_THEMES.imperial.sea;
  const html = [
    '<!doctype html><html lang="en"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">',
    `<meta http-equiv="Content-Security-Policy" content="${csp}">`,
    `<meta name="fon-atlas" content='${JSON.stringify(manifest)}'>`,
    "<title>Fabric of Nations map</title><style>",
    fontCss,
    `html,body{margin:0;height:100%;overflow:hidden;background:${sea};touch-action:none;-webkit-user-select:none;user-select:none;-webkit-touch-callout:none;-webkit-tap-highlight-color:transparent}`,
    "#map{position:absolute;left:0;top:0;right:0;bottom:0;overflow:hidden}",
    '</style></head><body><div id="map"></div>',
    `<script type="application/json" id="fon-catalog">${inlineJson(runtimeCatalog(provinceData, worldCatalog))}</script>`,
    `<script type="text/plain" id="fon-bundle">${bundleBytes.toString("base64")}</script>`,
    `<script type="text/plain" id="fon-relief">${relief.bytes.toString("base64")}</script>`,
    `<script type="text/plain" id="fon-ocean">${ocean.bytes.toString("base64")}</script>`,
    `<script type="text/plain" id="fon-decode-worker">${safeScript(decodeWorker)}</script>`,
    `<script>${safeScript(runtime)}</script></body></html>\n`,
  ].join("");
  return { html, catalog: provinceCatalogSource(provinceData), manifest, sizes: { relief, ocean, runtime } };
}

/** Read token values through esbuild, the same way the runtime receives them. */
async function bundleTokens() {
  const { code } = esbuild.transformSync(readFileSync(resolve(APP, "src/design/tokens.ts"), "utf8"), {
    loader: "ts",
    format: "cjs",
  });
  const module = { exports: {} };
  vm.runInNewContext(code, { module, exports: module.exports });
  return module.exports;
}

const normalise = (text) => text.replace(/\r\n/gu, "\n");

const { html, catalog, manifest, sizes } = await build();

if (checkOnly) {
  const stale = [];
  for (const [path, expected] of [
    [OUT_HTML, html],
    [OUT_CATALOG, catalog],
  ]) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      // Reported below as stale.
    }
    if (current === null || normalise(current) !== normalise(expected)) stale.push(path);
  }
  if (stale.length > 0) {
    console.error(`atlas is stale, run pnpm map:atlas:\n  ${stale.join("\n  ")}`);
    process.exitCode = 1;
  } else {
    console.log(`atlas is current: ${String(Buffer.byteLength(html))} bytes, sha256 ${sha256(normalise(html))}`);
  }
} else {
  writeFileSync(OUT_HTML, html);
  writeFileSync(OUT_CATALOG, catalog);
  console.log(`wrote ${OUT_HTML}: ${(Buffer.byteLength(html) / 1048576).toFixed(2)} MiB`);
  console.log(`  runtime ${(sizes.runtime.length / 1024).toFixed(0)} KiB`);
  console.log(
    `  relief ${String(sizes.relief.source.width)}x${String(sizes.relief.source.height)} -> ${String(manifest.textureSize[0])}x${String(manifest.textureSize[1])}, ${(sizes.relief.bytes.length / 1024).toFixed(0)} KiB`,
  );
  console.log(`  ocean ${(sizes.ocean.bytes.length / 1024).toFixed(0)} KiB`);
  console.log(`wrote ${OUT_CATALOG}: ${(Buffer.byteLength(catalog) / 1024).toFixed(0)} KiB`);
}
